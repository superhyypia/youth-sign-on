                Email address
            </li>

            <li>
                Emergency contact name and
                telephone number
            </li>

            <li>
                Relevant medical information
                voluntarily provided for the
                safe conduct of the spin
            </li>

            <li>
                The spin for which the rider
                registered and the date of
                registration
            </li>
