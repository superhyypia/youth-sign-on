            WhatsApp and QR codes
        </h2>

        <p>
            Ride Leaders can share a link to a
            spin registration page using WhatsApp
            or a QR code.
        </p>

        <p>
            These provide access to the registration
            page only. They do not contain or provide
            access to rider lists, emergency contact
            details or medical information.
        </p>

