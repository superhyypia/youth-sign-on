                Contact riders where necessary
                in connection with the spin
            </li>

            <li>
                Provide emergency contact
                information where required
            </li>

            <li>
                Make relevant medical information
                available where it may be important
                for rider safety
            </li>

            <li>
                Maintain basic participation
                records and statistics for the
                CI-Youths programme
            </li>
        </ul>

        <p>
            Personal information collected through
            the system is not intended to be used
            for advertising or unrelated marketing.
        </p>

