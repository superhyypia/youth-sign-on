            Detailed registration information is
            restricted to authorised CI-Youths
            administrators and the Ride Leader or
            Ride Leaders responsible for the
            relevant spin.
        </p>

        <p>
            Ride Leaders are instructed to treat
            rider information as confidential and
            not to unnecessarily copy, screenshot,
            forward or distribute rider lists.
        </p>

        <p>
            Medical and emergency contact
            information should only be accessed
            and used where required for the
            organisation or safe conduct of
            the spin.
        </p>

