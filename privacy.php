            Printed rider lists
        </h2>

        <p>
            A Ride Leader may print a rider list
            where this is useful for safely
            conducting a spin.
        </p>

        <p>
            Printed rider lists containing personal,
            emergency or medical information should
            be kept secure, used only for the
            relevant spin and securely destroyed
            when they are no longer required.
        </p>

